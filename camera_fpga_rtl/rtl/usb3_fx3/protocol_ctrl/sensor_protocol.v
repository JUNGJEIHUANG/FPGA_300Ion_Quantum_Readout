module sensor_protocol #(
    parameter    REG_DAT_WIDTH    = 8    ,    // register data width,
    parameter    DAT_PAIRS        = 16   ,    // sensor lvds channels
    parameter    DAT_WIDTH        = 12        // sensor data width of one lvds channel, supported : 12/14/16
)(
    // clock & reset
    input                                    clk                     ,    // same to clk of rx_pkg_decoder.v, usb30_interface.v/cl_serial.v
    input                                    rst                     ,    // same to rst of rx_pkg_decoder.v, usb30_interface.v/cl_serial.v
    input                                    clk_spi                 ,    // Fclk_spi<=Fclk,  // same to 'clk' if SCL/SPI_CLK can be generated by clk
    // protocol input signa
    input                                    i_prot_vld              ,    // clk domain, valid of i_prot_addr and i_prot_dat
    input             [15:0]                 i_prot_addr             ,    // clk domain, sensor protocol address
    input             [15:0]                 i_prot_dat              ,    // clk domain, sensor protocol data
    input                                    i_reg_ren               ,    // clk_spi domain
    input             [15:0]                 i_reg_raddr             ,    // clk_spi domain
    output            [REG_DAT_WIDTH-1:0]    o_reg_rdat              ,    // clk_spi domain

    //Used for different sensor
    output     reg    [7:0]                  o_adc_depth             ,    // need to be changed, according to:  8:8bit,9:9bit,10:10bit,11:11bit,12:12bit, 14:14bit,16:16bit 
    output     reg    [DAT_WIDTH-1:0]        o_synccode_1st          ,    // need to be changed base on different sensor, different DAT_WIDTH
    output     reg    [DAT_WIDTH-1:0]        o_synccode_2nd          ,    // need to be changed base on different sensor, different DAT_WIDTH
    output     reg    [DAT_WIDTH-1:0]        o_synccode_3rd          ,    // need to be changed base on different sensor, different DAT_WIDTH
    output     reg    [DAT_WIDTH-1:0]        o_synccode_4th_sof      ,    // need to be changed base on different sensor, different DAT_WIDTH
    output     reg    [DAT_WIDTH-1:0]        o_synccode_4th_sol      ,    // need to be changed base on different sensor, different DAT_WIDTH

    output     reg                           o_reg_sync_invert_en    ,    // EXT_VSYNC/EXT_VSYNC_MS level invert  enable 0: disable 1: enable
    output     reg                           o_reg_master            ,    // sensor master or slave mode select. 0: slave 1: master
    output     reg    [1:0]                  o_reg_hdr_mode_en       ,    // HDR mode en
    output     reg    [15:0]                 o_reg_frame_num         ,    // the burst number of master burst mode burst_frm_num[15:0] when scan_mode>1, the burst frame num must be even.
    output     reg    [15:0]                 o_reg_line_time         ,    // line_tim[13:0]
    output     reg    [15:0]                 o_reg_win_row_len       ,
    output     reg    [1:0]                  o_reg_flip_v_en         ,
    output     reg                           o_reg_msb_first_en      ,
    output     reg                           o_reg_flip_h_en         ,
    output     reg    [4:0]                  o_reg_n_mux             ,
    output     reg    [15:0]                 o_reg_training_word     ,
    output     reg    [15:0]                 o_reg_w_mux             ,
    output     reg    [7:0]                  o_reg_pwr_mode          ,
    output     reg    [7:0]                  o_reg_stream_en         ,
    output     reg    [7:0]                  o_reg_pll_en            ,
    output     reg    [7:0]                  o_reg_otp_prog_en       ,
    output     reg    [7:0]                  o_reg_pga_en            ,
    output     reg    [15:0]                 o_win_row_len           ,
    output     reg    [15:0]                 o_win_row_len_ddr       ,
    output     reg    [15:0]                 o_win_row_len_lp        ,
    output     reg    [15:0]                 o_win_col_len           ,
    output     reg    [15:0]                 o_lval_len              ,    // need to be changed base on different sensor, different DAT_PAIRS
    output     reg    [15:0]                 o_lval_len_ddr          ,    // need to be changed base on different sensor, image cashe and process
    output     reg    [15:0]                 o_lval_len_buf          ,    // need to be changed base on different sensor, image cashe and process
    output     reg    [DAT_PAIRS-1:0]        o_chan_vld                   // need to be changed base on different sensor, different DAT_PAIRS, different channel multiplexing
);

//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------
// Reg & wire
//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------

reg     [15:0]    burst_frm_num  ;
reg     [15:0]    ob_win_len     ;
reg               ob_win_en      ;
reg     [1:0]     n_mux          ;

//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------
// Assignment
//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------

//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------
// Main Codec
//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------

//base on sensor
//o_adc_depth changed according to:  8:8bit,9:9bit,10:10bit,11:11bit,12:12bit, 14:14bit,16:16bit 

always @(posedge clk or posedge rst)begin
    if (rst == 1) begin
        o_adc_depth    <= 'd12;
    end
    else begin
        o_adc_depth    <= 'd12;
    end
end

//o_synccode_  :  base on sensor, DAT_WIDTH : 12/14/16
always @(posedge clk or posedge rst) begin
    if (rst == 1) begin
        o_synccode_1st        <= 'hFFF;
        o_synccode_2nd        <= 'h000;
        o_synccode_3rd        <= 'h000;
        o_synccode_4th_sof    <= 'h800;
        o_synccode_4th_sol    <= 'hAB0;
    end
    else begin
        case(o_adc_depth)
            // 'd8:    begin
                        // o_synccode_1st        <= 'h0FF;
                        // o_synccode_2nd        <= 'h000;
                        // o_synccode_3rd        <= 'h000;
                        // o_synccode_4th_sof    <= 'h080;
                        // o_synccode_4th_sol    <= 'h0AB;
                    // end
            // 'd9:    begin
                        // o_synccode_1st        <= 'h;
                        // o_synccode_2nd        <= 'h;
                        // o_synccode_3rd        <= 'h;
                        // o_synccode_4th_sof    <= 'h;
                        // o_synccode_4th_sol    <= 'h;
                    // end
            // 'd10:   begin
                        // o_synccode_1st        <= 'h3FF;
                        // o_synccode_2nd        <= 'h000;
                        // o_synccode_3rd        <= 'h000;
                        // o_synccode_4th_sof    <= 'h200;
                        // o_synccode_4th_sol    <= 'h2AC;
                    // end
            // 'd11:   begin
                        // o_synccode_1st        <= 'h;
                        // o_synccode_2nd        <= 'h;
                        // o_synccode_3rd        <= 'h;
                        // o_synccode_4th_sof    <= 'h;
                        // o_synccode_4th_sol    <= 'h;
                    // end
            'd12:   begin
                        o_synccode_1st        <= 'hFFF;
                        o_synccode_2nd        <= 'h000;
                        o_synccode_3rd        <= 'h000;
                        o_synccode_4th_sof    <= 'h800;
                        o_synccode_4th_sol    <= 'hAB0;
                    end 
            // 'd14:   begin
                        // o_synccode_1st        <= 'h3FFF;
                        // o_synccode_2nd        <= 'h0000;
                        // o_synccode_3rd        <= 'h0000;
                        // o_synccode_4th_sof    <= 'h2000;
                        // o_synccode_4th_sol    <= 'h2AC0;
                    // end
            // 'd16:   begin
                        // o_synccode_1st        <= 'h;
                        // o_synccode_2nd        <= 'h;
                        // o_synccode_3rd        <= 'h;
                        // o_synccode_4th_sof    <= 'h;
                        // o_synccode_4th_sol    <= 'h;
                    // end
            default: ;
        endcase
    end
end

//Used for different sensor
always @(posedge clk or posedge rst) begin
    if (rst == 1) begin  // all value need to be the default register value of sensor
        o_reg_stream_en           <= 'd0;
        o_reg_sync_invert_en      <= 1'b0;        // 0: high valid                   sync_invert_en
        o_reg_master              <= 1'b0;        // 0: slave                        xmaster
        o_reg_hdr_mode_en         <= 2'd0;
        burst_frm_num             <= 16'h0001;    // 1: BURST_FRM_NUM                burst_frm_num
        o_reg_line_time           <= 16'h0234;    // 564:                            line_tim
        o_reg_win_row_len         <= 16'h0010;    // 16:                             win_all_len
        o_reg_flip_v_en           <= 2'd0;
        ob_win_len                <= 16'd0;
        ob_win_en                 <= 1'b0;
        o_reg_pwr_mode            <= 8'b0;        // 0: Normal mode
        o_reg_pll_en              <= 8'b0;        // pll en
        o_reg_otp_prog_en         <= 8'b0;        // otp
        o_reg_msb_first_en        <= 1'b0;        // 0: msb_first                    big_end_en
        o_reg_flip_h_en           <= 1'b0;        // 0: close                        flip_h
        n_mux                     <= 2'd3;        // 8 selected channels             n_mux
        o_reg_training_word       <= 16'h6E;      // 110 TP                          training_pattern
        o_reg_pga_en              <= 8'd0;
    end
    else begin
        if (i_prot_vld) begin
            case (i_prot_addr[15:0])
                16'h0000:       o_reg_stream_en                      <= i_prot_dat[7:0]; 

                16'h0002:   begin
                                o_reg_sync_invert_en                 <= i_prot_dat[1];     // EXT_VSYNC level invert  enable 0: disable 1: enable
                                o_reg_master                         <= i_prot_dat[0];     // sensor master or slave mode select. 0: slave 1: master
                            end
                16'h0003:       o_reg_hdr_mode_en                    <= i_prot_dat[3:2];

                16'h0020:       burst_frm_num[7:0]                   <= i_prot_dat[7:0];
                16'h0021:       burst_frm_num[15:8]                  <= i_prot_dat[7:0];    // the burst number of master burst mode , burst_frm_num[15:0] , burst_frm_num >= 16'd1

                16'h0070:       o_reg_line_time[7:0]                 <= i_prot_dat[7:0];
                16'h0071:       o_reg_line_time[15:8]                <= i_prot_dat[7:0];    // line_tim[15:0]

                16'h00B2:       o_reg_win_row_len[7:0]               <= i_prot_dat[7:0];
                16'h00B3:       o_reg_win_row_len[15:8]              <= i_prot_dat[7:0];    // window length, unit row win_all_len[9:0]

                16'h0110:       o_reg_flip_v_en                      <= i_prot_dat[6:5];

                16'h0120:       ob_win_len[7:0]                      <= i_prot_dat[7:0];
                16'h0121:       ob_win_len[15:8]                     <= i_prot_dat[7:0];    // ob_win_len[9:0]

                16'h0330:       ob_win_en                            <= i_prot_dat[1];

                16'h0370:   begin
                                o_reg_pwr_mode                       <= i_prot_dat[7:0];      // [1:0] 0: Normal mode ; 2：Low power mode
                            end

                16'h03EA:       o_reg_pll_en                         <= i_prot_dat[7:0];

                16'h03EE:       o_reg_otp_prog_en                    <= i_prot_dat[7:0];

                16'h0400:   begin
                                o_reg_msb_first_en                   <= i_prot_dat[0];     // bot_big_end_en  0: LSB ; 1: MSB
                                o_reg_flip_h_en                      <= i_prot_dat[6];      // horizontal flip mode select 0: close 1: flip
                            end
                16'h0402:       n_mux                                <= i_prot_dat[1:0];    // Number of selected channels used for readout  range 0~3

                16'h0405:       o_reg_training_word[7:0]             <= i_prot_dat[7:0];
                16'h0406:       o_reg_training_word[15:8]            <= i_prot_dat[3:0];    // training pattern data [11:0]

                16'h202E:       o_reg_pga_en                         <= i_prot_dat[7:0];    // training pattern data [11:0]

                default: ;
            endcase
        end
    end
end

// Row to PC
always @(posedge clk or posedge rst)begin
    if (rst == 1) begin
        o_win_row_len    <= 'd8;
    end
    else begin
        if(o_reg_hdr_mode_en == 2'd0) begin
            if(ob_win_en == 1'b1) begin
                o_win_row_len    <= (o_reg_win_row_len + ob_win_len) << 2;
            end
            else begin
                o_win_row_len    <= o_reg_win_row_len << 2;
            end
        end
        else begin
            if(ob_win_en == 1'b1) begin
                o_win_row_len    <= (o_reg_win_row_len + ob_win_len) << 2;
            end
            else begin
                o_win_row_len    <= o_reg_win_row_len << 2;
            end
        end
    end
end

// Column to PC
always @(posedge clk or posedge rst) begin
    if (rst == 1) begin
        o_win_col_len    <= 'd2176;
    end
    else begin
        o_win_col_len    <= 'd2176;
    end
end

// Row to DDR
always @(posedge clk or posedge rst)begin
    if (rst == 1) begin
        o_win_row_len_ddr    <= 'd2;    // to DDR
    end
    else begin
        if(o_reg_hdr_mode_en == 2'd0) begin
            o_win_row_len_ddr    <= o_win_row_len >> 2;
        end
        else begin
            o_win_row_len_ddr    <= o_win_row_len >> 1;
        end

    end
end

// Row to low power mode
always @(posedge clk or posedge rst)begin
    if (rst == 1) begin
        o_win_row_len_lp    <= 'd8;
    end
    else begin
        if(ob_win_en == 1'b1) begin
            o_win_row_len_lp    <= o_reg_win_row_len + ob_win_len;
        end
        else begin
            o_win_row_len_lp    <= o_reg_win_row_len;
        end
    end
end


// Line valid length from sensor
always @(posedge clk or posedge rst) begin
    if (rst == 1) begin
        o_lval_len    <= 'd1088;
    end
    else begin
        o_lval_len    <= o_reg_w_mux;
    end
end

// Line valid length to DDR
always @(posedge clk or posedge rst)begin
    if (rst == 1'b1)begin
        o_lval_len_ddr    <= 'd272;
    end
    else begin 
        o_lval_len_ddr    <= 'd272;
    end
end

// Lien valid length to image buffer
always @(posedge clk or posedge rst)begin
    if (rst == 1'b1)begin
        o_lval_len_buf    <= 'd1088;
    end
    else begin 
        o_lval_len_buf    <= 'd1088;
    end
end

// Channel valid
always @(posedge clk or posedge rst) begin
    if (rst == 1'b1) begin
        o_chan_vld    <= {DAT_PAIRS{1'b1}};
    end
    else begin
        case(n_mux)
            'd0:     o_chan_vld    <= {2{7'd0,1'b1}};
            'd1:     o_chan_vld    <= {4{3'd0,1'b1}};
            'd2:     o_chan_vld    <= {8{1'b0,1'b1}};
            'd3:     o_chan_vld    <= {DAT_PAIRS{1'b1}};
            default: o_chan_vld    <= {DAT_PAIRS{1'b1}};
        endcase
    end
end

// o_reg_n_mux & o_reg_w_mux
always @(posedge clk or posedge rst) begin
    if (rst == 1'b1) begin
        o_reg_n_mux    <= 'd8;
        o_reg_w_mux    <= 'd1088;
    end
    else begin
        case(n_mux)
            'd0:    begin
                        o_reg_n_mux    <= 'd1;
                        o_reg_w_mux    <= 'd8704;
                    end
            'd1:    begin
                        o_reg_n_mux    <= 'd2;
                        o_reg_w_mux    <= 'd4352;
                    end
            'd2:    begin
                        o_reg_n_mux    <= 'd4;
                        o_reg_w_mux    <= 'd2176;
                    end
            'd3:    begin
                        o_reg_n_mux    <= 'd8;
                        o_reg_w_mux    <= 'd1088;
                    end
            default:begin
                        o_reg_n_mux    <= 'd8;
                        o_reg_w_mux    <= 'd1088;
                    end
        endcase
    end
end

// o_reg_frame_num
always @(posedge clk or posedge rst)begin
    if (rst == 1'b1)begin
        o_reg_frame_num    <= 'd2;
    end
    else begin
        o_reg_frame_num    <= burst_frm_num;
    end
end

