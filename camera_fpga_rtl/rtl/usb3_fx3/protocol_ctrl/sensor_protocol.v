// Simple Dual Port RAM
// Port A   Width 8  Depth 16384
// Port A   Always Enabled
// Port B   Width 8  Depth 16384
// Port B   Use ENB Pin
// output register    no
bram_w8d16384_sdpr    u_bram_sensor_register
(
    .clka     (clk                          ),
    .wea      (i_prot_vld                   ),
    .addra    (i_prot_addr[13:0]            ),
    .dina     (i_prot_dat[REG_DAT_WIDTH-1:0]),
    .clkb     (clk_spi                      ),
    .enb      (i_reg_ren                    ),
    .addrb    (i_reg_raddr[13:0]            ),
    .doutb    (o_reg_rdat[REG_DAT_WIDTH-1:0])
);

