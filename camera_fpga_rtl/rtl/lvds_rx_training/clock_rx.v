module clock_rx #(
    parameter    CLKDDR_PAIRS             = 1    // sensor clk_ddr pairs 
)(
    input            [CLKDDR_PAIRS - 1:0]    i_CLK_DDR_IN_P ,
    input            [CLKDDR_PAIRS - 1:0]    i_CLK_DDR_IN_N ,
    input                                    i_sys_rst_n    ,
    output                                   o_clk_check_pll,
    output           [CLKDDR_PAIRS - 1:0]    o_clk_rx       ,
    output           [CLKDDR_PAIRS - 1:0]    o_clk_ddr      ,
    output    reg    [CLKDDR_PAIRS - 1:0]    o_rst_rx        
);

//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------
// Parameter
//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------

//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------
// Reg & Wire
//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------

wire              clk_ddr_in[CLKDDR_PAIRS - 1:0] ;
reg     [9:0]     cnt_rst_rx[CLKDDR_PAIRS - 1:0] ;

//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------
// Assignment
//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------

//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------
// Main Code
//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------

genvar    j;
generate
    for (j = 0; j < CLKDDR_PAIRS; j = j+1) begin:loop_rst_rx
    always @(posedge o_clk_rx[j] or negedge i_sys_rst_n) begin
        if (i_sys_rst_n == 1'b0)begin
            cnt_rst_rx[j]      <= 10'd0;
            o_rst_rx[j]        <= 1'b1;
        end
        else begin
            if(cnt_rst_rx[j][9]  == 1'b1)begin
                o_rst_rx[j]             <= 1'b0;
            end 
            else begin
                o_rst_rx[j]             <= 1'b1;
                cnt_rst_rx[j]           <= cnt_rst_rx[j] + 1'b1;
            end  
        end
    end
    end
endgenerate

//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------
// Instance
//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------

genvar    i;
generate
    for (i = 0; i < CLKDDR_PAIRS; i = i+1) begin:loop_clk
        IBUFDS #(
            .DIFF_TERM       ("TRUE"           ),    // Differential Termination
            .IBUF_LOW_PWR    ("FALSE"          ),    // Low power="TRUE", Highest performance="FALSE"
            .IOSTANDARD      ("DEFAULT"        )     // Specify the input I/O standard
        ) u_IBUFDS_clk_ddr_in
       (
            .O               (clk_ddr_in[i]    ),
            .I               (i_CLK_DDR_IN_P[i]),
            .IB              (i_CLK_DDR_IN_N[i])
        );

        BUFIO    BUFG_CLK_DDR
		(
            .O               (o_clk_ddr[i]  ),    // 1-bit output: Clock output (connect to I/O clock loads).
            .I               (clk_ddr_in[i] )     // 1-bit input: Clock input (connect to an IBUF or BUFMR).
        );
 
        BUFR #(
            .BUFR_DIVIDE     ("4"           ),
            .SIM_DEVICE      ("7SERIES"     )
        ) u_bufr_txdiv4
        (
            .I               (clk_ddr_in[i] ),
            .CLR             (1'b0          ),
            .CE              (1'b1          ),
            .O               (o_clk_rx[i]   )
        );
    end
endgenerate

BUFG BUFG_CLK_PLL (
    .O               (o_clk_check_pll),
    .I               (clk_ddr_in[0]  )
);

//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------
// CDC
//-------------------------------------------------------------------------------------------------------------------------------------------------------------------------

endmodule
